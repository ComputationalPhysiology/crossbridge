"""
Tewari et al. (2016) rat cardiac myofilament model.

Based on: Tewari, S.G., Bugenhagen, S.M., Vinnakota, K.C., Rice, J.J., Janssen,
P.M.L., & Beard, D.A. (2016). Influence of metabolic dysfunction on cardiac
mechanics in decompensated hypertrophy and heart failure. Journal of Molecular
and Cellular Cardiology, 94, 162-175. https://doi.org/10.1016/j.yjmcc.2016.04.003

and the crossbridge model it extends: Tewari, S.G., Bugenhagen, S.M., Palmer,
B.M., & Beard, D.A. (2016). Dynamics of cross-bridge cycling, ATP hydrolysis,
force generation, and deformation in cardiac muscle. Journal of Molecular and
Cellular Cardiology, 96, 11-25. https://doi.org/10.1016/j.yjmcc.2015.02.006

A strain-dependent crossbridge cycle -- permissible P, loosely attached A1,
strongly attached A2, post-powerstroke A3 -- whose attached states are each a
distribution over crossbridge strain, reduced to ODEs by keeping the zeroth,
first and second moments of each distribution (``p{state}_{order}``). The
metabolites MgATP, MgADP and Pi enter the rate constants (product inhibition),
and temperature enters through Q10 factors. Calcium activation follows Rice et
al. (2008): low- and high-affinity troponin C (``CaL``, ``CaH``, bound in the
non-overlap and overlap regions of the thin filament) set the rate of the
non-permissible -> permissible transition (``N`` -> P), with the force
generated by crossbridges slowing Ca2+ unbinding (the paper's Appendix B).
Active tension is the crossbridge force scaled by thick-filament overlap.

**The reference temperature.** Table B.1's crossbridge rates and stiffnesses
are the rat values of Tewari et al. (2015) at 17 degC, scaled to temperature T
by ``Q ** ((T - T_ref) / 10)``. Eqs. (IV) and (VI) print ``(T - 37.5) / 10``
for the activation rates; read that way, the model needs about twice the
calcium the paper's own results show (Table E.1, Figs. 2-4), and twitches at
4 Hz reach 12 kPa instead of the paper's ~60. Taking Table B.1's activation
rates at 17 degC as well -- ``T_ref_act`` -- reproduces Table E.1's Ca50 and
Hill coefficients at all five sarcomere lengths to within 0.16 uM and 1.6, and
the 4 Hz twitch. Set ``T_ref_act = 37.5`` for the reading as printed.

**Departures from the paper**, both guards that leave the physiological range
untouched: the filament overlap is floored at zero (the Rice formula turns
negative below SL = L_thin), and the force factor ``f = 1 - zeta F/F_max`` of
Ca2+ unbinding is floored at zero, since a large stretch can raise F past
F_max/zeta, where the off-rate would turn negative and troponin occupancy run
away.

**Numerical scheme.** Given the inputs and the three nonlinear coefficients --
``f`` and the rates of N -> P and P -> N -- the twelve states obey a linear
system, which is solved exactly over a sub-step with a matrix exponential (of
the system augmented by its constant term, so it needs no solve). The
coefficients are taken at the sub-step's midpoint, from a half-step predictor
(the exponential midpoint rule), which keeps the error second order in the
sub-step through the steep (n_beta = 15) troponin switch. Sub-steps are at
most ``_TARGET_SUBSTEP``; calcium, SL and dSL are held over the call.

Examples
--------
>>> import numpy as np
>>> from crossbridge import Tewari2016
>>>
>>> model = Tewari2016(num_cells=10)
>>> model.advance_step(1e-3, Ca_val=2.0, SL_vals=np.full(10, 2.2))
>>> Ta = model.get_active_tension()  # shape (10,), kPa
"""

from pathlib import Path

import numpy as np
import numpy.typing as npt

from ._linalg import expm_batch
from .base import CardiacActivationModel

#: Longest sub-step [s] over which the nonlinear coefficients are held.
_TARGET_SUBSTEP = 1e-4  # [s]

# Rows/columns of the linear system; the last one carries the constant term.
_CaL, _CaH, _N = 0, 1, 2
_P10, _P11, _P12, _P20, _P21, _P22, _P30, _P31, _P32 = range(3, 12)
_ONE = 12
_SIZE = 13

#: The moment states, in the order of the linear system.
_MOMENTS = ("p1_0", "p1_1", "p1_2", "p2_0", "p2_1", "p2_2", "p3_0", "p3_1", "p3_2")


class Tewari2016(CardiacActivationModel):
    """
    Vectorized Tewari et al. (2016) rat myofilament model.

    Attributes
    ----------
    CaL, CaH : ndarray, shape (num_cells,)
        Fraction of low- and high-affinity troponin C with Ca2+ bound.
    N : ndarray, shape (num_cells,)
        Fraction of crossbridges in the non-permissible state.
    p1_0, p1_1, p1_2, p2_0, ..., p3_2 : ndarray, shape (num_cells,)
        Moments of the strain distributions of the attached states A1, A2, A3:
        ``p{k}_0`` is the fraction in state k [-], ``p{k}_1`` its first moment
        [um] and ``p{k}_2`` its second [um^2]. Strain is measured in sarcomere
        length, as in the paper's code: the moments advance with dSL/dt.

    The permissible fraction ``P = 1 - N - p1_0 - p2_0 - p3_0`` is derived.
    Sarcomere length is an input, as in every model of this package; the
    paper's muscle model (series element, viscosity, passive force -- its
    Eq. (V)) belongs to the caller, and `get_passive_tension` supplies the
    passive part. `demo/reproduce_figures_tewari2016.py` builds it.
    """

    ODE_FILE = Path(__file__).with_name("tewari2016.ode")

    CaL: npt.NDArray[np.float64]
    CaH: npt.NDArray[np.float64]
    N: npt.NDArray[np.float64]
    p1_0: npt.NDArray[np.float64]
    p1_1: npt.NDArray[np.float64]
    p1_2: npt.NDArray[np.float64]
    p2_0: npt.NDArray[np.float64]
    p2_1: npt.NDArray[np.float64]
    p2_2: npt.NDArray[np.float64]
    p3_0: npt.NDArray[np.float64]
    p3_1: npt.NDArray[np.float64]
    p3_2: npt.NDArray[np.float64]

    #: Attributes that evolve; see `CardiacActivationModel.get_state`.
    _state_names = (
        "CaL",
        "CaH",
        "N",
        *_MOMENTS,
        "_SL_prev",
        "_SL_curr",
        "_has_prev_step",
    )

    def __init__(self, num_cells: int, Ta_max: float = 1.0, params: dict | None = None):
        """
        Initialize the Tewari2016 model.

        Parameters
        ----------
        num_cells : int
            Number of independent cells / FEM integration points.
        Ta_max : float, optional
            Unused. Tension follows from the crossbridge stiffnesses
            (`kstiff1`, `kstiff2`). Kept for API compatibility with
            `CardiacActivationModel`. Default is 1.0.
        params : dict, optional
            Parameter overrides. Keys should match those returned by
            `default_parameters()`.
        """
        super().__init__(int(num_cells), Ta_max, params)

        self.p = type(self).default_parameters()
        if params:
            self.p.update(params)
        p = self.p
        self.dt = p["dt"]

        # Rate constants at temperature T and the metabolite levels, which
        # are parameters and so fixed for the model's lifetime.
        def q(Q: float, T_ref: float) -> float:
            return Q ** ((p["T"] - T_ref) / 10.0)

        T_xb, T_act = p["T_ref"], p["T_ref_act"]
        g_Pi = p["Pi"] / p["K_Pi"]
        g_ATP = p["MgATP"] / p["K_MgATP"]
        g_ADP = p["MgADP"] / p["K_MgADP"]
        self._ka = p["ka"] * q(p["Q_XB1"], T_xb)
        self._k1 = p["k1"] * q(p["Q_XB1"], T_xb) / (1.0 + g_Pi)
        self._kd = p["kd"] * q(p["Q_XB2"], T_xb) * g_Pi / (1.0 + g_Pi)
        self._km1 = p["km1"] * q(p["Q_XB2"], T_xb)
        self._k2 = p["k2"] * q(p["Q_XB3"], T_xb)
        self._k3 = p["k3"] * q(p["Q_XB3"], T_xb) * g_ATP / (1.0 + g_ATP + g_ADP)
        self._km2 = p["km2"] * g_ADP / (1.0 + g_ADP + g_ATP)
        self._kstiff1 = p["kstiff1"] * q(p["Q_XB4"], T_xb)
        self._kstiff2 = p["kstiff2"] * q(p["Q_XB5"], T_xb)
        self._kon = p["kon"] * q(p["Q_kon"], T_act)
        self._koffL = p["koffL"] * q(p["Q_koff"], T_act)
        self._koffH = p["koffH"] * q(p["Q_koff"], T_act)
        self._kNP = p["kNP"] * q(p["Q_kNP"], T_act)
        self._kPN = p["kPN"] * q(p["Q_kPN"], T_act)

        # Eq. (VIII): the strain-free steady-state A3 occupancy of the cycle
        # P -> A1 -> A2 -> A3 -> P, times the powerstroke force (King-Altman).
        ka, kd, k1, km1 = self._ka, self._kd, self._k1, self._km1
        k2, km2, k3 = self._k2, self._km2, self._k3
        denominator = (
            k1 * k2 * k3
            + k2 * k3 * kd
            + k1 * k2 * ka
            + k1 * k3 * ka
            + k2 * k3 * ka
            + k3 * km1 * kd
            + k1 * km2 * ka
            + k3 * km1 * ka
            + km1 * km2 * kd
            + km1 * km2 * ka
        )
        self._F_max = self._kstiff2 * p["dr"] * k1 * k2 * ka / denominator

        self.reset()

    @classmethod
    def default_parameters(cls) -> dict:
        """
        Return default parameters: Table B.1 (myofilament) and Table C.1
        (passive force) of Tewari et al. (2016), with the metabolite
        dissociation constants of Tewari et al. (2015) for rat.

        Crossbridge rates and stiffnesses are given at `T_ref` (17 degC) and
        activation rates at `T_ref_act` (17 degC; see the module docstring);
        the model runs at `T`. The default conditions are those of the
        paper's Fig. 2: 37.5 degC, MgATP 8 mM, MgADP 18 uM, Pi 0.6 mM. Strain
        and lengths are in um, stiffnesses in kPa/um, calcium in uM and the
        metabolites in mM. `kd` and `km2` are the table's, already scaled
        (by 2.5 and 10) from the 2015 values, as its footnotes say.
        """
        p: dict = {}
        # Numerical: a *suggested* coupling dt; advance_step sub-steps
        # internally whatever the step it is given.
        p["dt"] = 1e-3  # [s]

        # SL0 only sets the unit of Lambda = SL / SL0 in which Ka is reported:
        # the resting length of Table C.1, also the TriSeg reference length of
        # the paper's heart model, where SL = 1.9 exp(fibre strain).
        p["SL0"] = 1.9  # [um]

        # Conditions
        p["T"] = 37.5  # [degC]
        p["T_ref"] = 17.0  # [degC] crossbridge rates and stiffnesses
        p["T_ref_act"] = 17.0  # [degC] activation rates (module docstring)
        p["MgATP"] = 8.0  # [mM]
        p["MgADP"] = 0.018  # [mM]
        p["Pi"] = 0.6  # [mM]
        p["K_MgATP"] = 0.4897  # [mM]
        p["K_MgADP"] = 0.194  # [mM]
        p["K_Pi"] = 4.0  # [mM]

        # Sarcomere geometry
        p["L_thick"] = 1.67  # [um]
        p["L_thin"] = 1.2  # [um]
        p["L_bare"] = 0.1  # [um]

        # Thin-filament activation (Rice et al. 2008, refit)
        p["kon"] = 100.0  # [1/(uM s)]
        p["koffL"] = 4218.5  # [1/s]
        p["koffH"] = 156.5  # [1/s]
        p["zeta"] = 0.23  # [-] force sensitivity of Ca2+ unbinding
        p["beta50"] = 0.5  # [-]
        p["n_beta"] = 15.0  # [-]
        p["Q_kon"] = 1.5  # [-]
        p["Q_koff"] = 1.3  # [-]
        p["kNP"] = 329.2  # [1/s]
        p["kPN"] = 50.0  # [1/s]
        p["Q_kNP"] = 1.6  # [-]
        p["Q_kPN"] = 1.6  # [-]

        # Crossbridge cycle
        p["ka"] = 294.1  # [1/s]
        p["kd"] = 88.9  # [1/s]
        p["k1"] = 10.2  # [1/s]
        p["km1"] = 10.3  # [1/s]
        p["k2"] = 88.6  # [1/s]
        p["km2"] = 20.9  # [1/s]
        p["k3"] = 35.6  # [1/s]
        p["alpha1"] = 10.0  # [1/um]
        p["alpha2"] = 9.0  # [1/um]
        p["alpha3"] = 59.3  # [1/um^2]
        p["s3"] = 9.9e-3  # [um]
        p["kstiff1"] = 2827.1  # [kPa/um]
        p["kstiff2"] = 51871.0  # [kPa/um]
        p["dr"] = 0.010  # [um] powerstroke
        p["Q_XB1"] = 3.82  # [-] ka, k1
        p["Q_XB2"] = 2.39  # [-] kd, km1
        p["Q_XB3"] = 6.73  # [-] k2, k3
        p["Q_XB4"] = 1.34  # [-] kstiff1
        p["Q_XB5"] = 1.44  # [-] kstiff2

        # Passive force (Rice et al. 2008, Table C.1)
        p["SL_rest"] = 1.9  # [um]
        p["PCon_titin"] = 0.002  # [-]
        p["PExp_titin"] = 10.0  # [1/um]
        p["PCon_collagen"] = 0.02  # [-]
        p["PExp_collagen"] = 70.0  # [1/um]
        p["SL_collagen"] = 2.25  # [um]
        p["sigma_pas"] = 7.0  # [kPa]

        # Initialization helper (not a model parameter): the diastolic Ca at
        # which reset() puts troponin at its steady state.
        p["Ca0"] = 0.1  # [uM]
        return p

    def reset(self) -> None:
        """
        Reset to the quiescent state: no crossbridges attached, all of them
        non-permissible (N = 1), and troponin C at its steady state for
        `params["Ca0"]` without force (f = 1).
        """
        n = self.num_cells
        Ca0 = max(self.p["Ca0"], 0.0)
        self.CaL = np.full(n, self._kon * Ca0 / (self._kon * Ca0 + self._koffL))
        self.CaH = np.full(n, self._kon * Ca0 / (self._kon * Ca0 + self._koffH))
        self.N = np.ones(n)
        for name in _MOMENTS:
            setattr(self, name, np.zeros(n))

        self._SL_prev = np.full(n, self.p["SL0"])
        self._SL_curr = np.full(n, self.p["SL0"])
        self._has_prev_step = False

        self._prev_bound_ca = np.zeros(n)
        self._last_dt = 0.0

    # ------------------------------------------------------------------
    # Helpers
    # ------------------------------------------------------------------

    def _overlap(
        self, SL: npt.NDArray[np.float64]
    ) -> tuple[npt.NDArray[np.float64], npt.NDArray[np.float64]]:
        """Eqs. (I)-(II): fractional thick- and thin-filament overlap."""
        p = self.p
        ov_z = np.minimum(p["L_thick"] / 2.0, SL / 2.0)
        ov_m = np.maximum(SL / 2.0 - (SL - p["L_thin"]), p["L_bare"] / 2.0)
        L_ov = np.maximum(ov_z - ov_m, 0.0)
        return 2.0 * L_ov / (p["L_thick"] - p["L_bare"]), L_ov / p["L_thin"]

    def _crossbridge_force(self, x: npt.NDArray[np.float64]) -> npt.NDArray[np.float64]:
        """F_XB of Eq. (7) of Tewari et al. (2015) [kPa], before overlap scaling."""
        return self._kstiff1 * (x[_P21] + x[_P31]) + self._kstiff2 * self.p["dr"] * x[_P30]

    def _coefficients(
        self, x: npt.NDArray[np.float64], OV_thin: npt.NDArray[np.float64]
    ) -> tuple[npt.NDArray[np.float64], npt.NDArray[np.float64], npt.NDArray[np.float64]]:
        """(f, k_NP, k_PN): the nonlinear coefficients at state `x`, shape (12, n)."""
        p = self.p
        f = np.maximum(1.0 - p["zeta"] * self._crossbridge_force(x) / self._F_max, 0.0)
        # Eq. (III), as sqrt(TR^n / (TR^n + beta50^n)): the printed form
        # divides by TrpReg, which is zero without calcium.
        TR_n = np.maximum((1.0 - OV_thin) * x[_CaL] + OV_thin * x[_CaH], 0.0) ** p["n_beta"]
        beta_NP = np.sqrt(TR_n / (TR_n + p["beta50"] ** p["n_beta"]))
        beta_PN = 1.0 / np.maximum(beta_NP, 0.01)  # min(100, 1 / beta_NP)
        return f, self._kNP * beta_NP, self._kPN * beta_PN

    def _system(
        self,
        Ca: npt.NDArray[np.float64],
        v: npt.NDArray[np.float64],
        f: npt.NDArray[np.float64],
        k_NP: npt.NDArray[np.float64],
        k_PN: npt.NDArray[np.float64],
    ) -> npt.NDArray[np.float64]:
        """
        The (n, 13, 13) matrix of d[x, 1]/dt for frozen coefficients.

        Rows 3-11 are Eq. (11) of Tewari et al. (2015) for i = 0, 1, 2, with
        P = 1 - N - p1_0 - p2_0 - p3_0 and the moments of order 3 and 4
        dropped; its last term on A3 reads alpha3 * p3^(i+2), the alpha3 the
        printed equation omits.
        """
        p = self.p
        a1, a2, a3, s3 = p["alpha1"], p["alpha2"], p["alpha3"], p["s3"]
        ka, kd, k1, km1 = self._ka, self._kd, self._k1, self._km1
        k2, km2, k3 = self._k2, self._km2, self._k3
        k3s = k3 * (1.0 + a3 * s3 * s3)

        M = np.zeros((self.num_cells, _SIZE, _SIZE))
        # Eq. (VI): troponin C
        M[:, _CaL, _CaL] = -self._kon * Ca - f * self._koffL
        M[:, _CaL, _ONE] = self._kon * Ca
        M[:, _CaH, _CaH] = -self._kon * Ca - f * self._koffH
        M[:, _CaH, _ONE] = self._kon * Ca
        # dN/dt = -k_NP N + k_PN P
        M[:, _N, _N] = -k_NP - k_PN
        M[:, _N, _P10] = M[:, _N, _P20] = M[:, _N, _P30] = -k_PN
        M[:, _N, _ONE] = k_PN
        # A1, attached at zero strain from P
        M[:, _P10, _N] = -ka
        M[:, _P10, _P10] = -ka - kd - k1
        M[:, _P10, _P11] = k1 * a1
        M[:, _P10, _P12] = -0.5 * k1 * a1 * a1
        M[:, _P10, _P20] = -ka + km1
        M[:, _P10, _P21] = km1 * a1
        M[:, _P10, _P22] = 0.5 * km1 * a1 * a1
        M[:, _P10, _P30] = -ka
        M[:, _P10, _ONE] = ka
        M[:, _P11, _P10] = v
        M[:, _P11, _P11] = -kd - k1
        M[:, _P11, _P12] = k1 * a1
        M[:, _P11, _P21] = km1
        M[:, _P11, _P22] = km1 * a1
        M[:, _P12, _P11] = 2.0 * v
        M[:, _P12, _P12] = -kd - k1
        M[:, _P12, _P22] = km1
        # A2
        M[:, _P20, _P10] = k1
        M[:, _P20, _P11] = -k1 * a1
        M[:, _P20, _P12] = 0.5 * k1 * a1 * a1
        M[:, _P20, _P20] = -km1 - k2
        M[:, _P20, _P21] = -km1 * a1 + k2 * a2
        M[:, _P20, _P22] = -0.5 * km1 * a1 * a1 - 0.5 * k2 * a2 * a2
        M[:, _P20, _P30] = km2
        M[:, _P21, _P11] = k1
        M[:, _P21, _P12] = -k1 * a1
        M[:, _P21, _P20] = v
        M[:, _P21, _P21] = -km1 - k2
        M[:, _P21, _P22] = -km1 * a1 + k2 * a2
        M[:, _P21, _P31] = km2
        M[:, _P22, _P12] = k1
        M[:, _P22, _P21] = 2.0 * v
        M[:, _P22, _P22] = -km1 - k2
        M[:, _P22, _P32] = km2
        # A3, detaching at a rate growing with strain either side of -s3
        M[:, _P30, _P20] = k2
        M[:, _P30, _P21] = -k2 * a2
        M[:, _P30, _P22] = 0.5 * k2 * a2 * a2
        M[:, _P30, _P30] = -km2 - k3s
        M[:, _P30, _P31] = -2.0 * k3 * a3 * s3
        M[:, _P30, _P32] = -k3 * a3
        M[:, _P31, _P21] = k2
        M[:, _P31, _P22] = -k2 * a2
        M[:, _P31, _P30] = v
        M[:, _P31, _P31] = -km2 - k3s
        M[:, _P31, _P32] = -2.0 * k3 * a3 * s3
        M[:, _P32, _P22] = k2
        M[:, _P32, _P31] = 2.0 * v
        M[:, _P32, _P32] = -km2 - k3s
        return M

    def _get_x(self) -> npt.NDArray[np.float64]:
        return np.stack([self.CaL, self.CaH, self.N, *(getattr(self, m) for m in _MOMENTS)])

    def _set_x(self, x: npt.NDArray[np.float64]) -> None:
        self.CaL, self.CaH, self.N = x[_CaL], x[_CaH], x[_N]
        for i, name in enumerate(_MOMENTS):
            setattr(self, name, x[_P10 + i])

    def _advance(
        self,
        x: npt.NDArray[np.float64],
        Ca: npt.NDArray[np.float64],
        v: npt.NDArray[np.float64],
        OV_thin: npt.NDArray[np.float64],
        h: float,
    ) -> npt.NDArray[np.float64]:
        """One exponential-midpoint sub-step of length h; x has shape (12, n)."""
        x1 = np.vstack([x, np.ones(self.num_cells)]).T  # (n, 13)

        def solve(coefficients, step):
            M = self._system(Ca, v, *coefficients)
            return np.einsum("nij,nj->in", expm_batch(M, step), x1)[:_ONE]

        x_half = solve(self._coefficients(x, OV_thin), 0.5 * h)
        return solve(self._coefficients(x_half, OV_thin), h)

    # ------------------------------------------------------------------
    # Public interface (CardiacActivationModel)
    # ------------------------------------------------------------------

    def advance_step(
        self,
        dt: float,
        Ca_val: float | npt.NDArray[np.float64],
        SL_vals: float | npt.NDArray[np.float64],
        dSL_vals: float | npt.NDArray[np.float64] | None = None,
    ) -> None:
        """
        Advance the model by one time step.

        Parameters
        ----------
        dt : float
            Time step [s]. Any length: it is split into sub-steps of at most
            `_TARGET_SUBSTEP`, with Ca_val, SL_vals and dSL_vals held fixed
            (zero-order hold) across it.
        Ca_val : float or np.ndarray, shape (num_cells,)
            Intracellular calcium concentration [uM].
        SL_vals : float or np.ndarray, shape (num_cells,)
            Sarcomere lengths [um].
        dSL_vals : float or np.ndarray, shape (num_cells,) or None
            Sarcomere length rate of change [um/s], the velocity that strains
            attached crossbridges. If None, estimated from the sarcomere
            length recorded on the previous call (zero on the first).
        """
        self._begin_step(dt)
        n = self.num_cells

        SL = np.broadcast_to(np.asarray(SL_vals, dtype=float), (n,)).copy()
        Ca = np.maximum(np.broadcast_to(np.asarray(Ca_val, dtype=float), (n,)), 0.0)
        if dSL_vals is not None:
            v = np.broadcast_to(np.asarray(dSL_vals, dtype=float), (n,)).copy()
        elif self._has_prev_step:
            v = (SL - self._SL_prev) / dt
        else:
            v = np.zeros(n)

        _, OV_thin = self._overlap(SL)
        n_sub = max(1, int(np.ceil(dt / _TARGET_SUBSTEP - 1e-9)))
        h = dt / n_sub
        x = self._get_x()
        for _ in range(n_sub):
            x = self._advance(x, Ca, v, OV_thin, h)
        self._set_x(x)

        self._SL_prev = SL
        self._SL_curr = SL
        self._has_prev_step = True

    def get_active_tension(self) -> npt.NDArray[np.float64]:
        """
        Active tension [kPa]: the crossbridge force times thick-filament
        overlap, F_act = OV_thick * (kstiff1 (p2_1 + p3_1) + kstiff2 dr p3_0).
        """
        OV_thick, _ = self._overlap(self._SL_curr)
        return OV_thick * self._crossbridge_force(self._get_x())

    def get_active_stiffness(self) -> npt.NDArray[np.float64]:
        r"""
        Active stiffness [kPa per unit Lambda = SL/SL0].

        .. math::
            K_a = SL_0 \, OV_{thick}\, k_{stiff,1} \left(p_2^0 + p_3^0\right)

        Velocity enters the model only through the moment equations,
        :math:`\dot p_k^1 = v\,p_k^0 + \ldots` and
        :math:`\dot p_k^2 = 2 v\,p_k^1 + \ldots`, and tension depends on the
        first moments of A2 and A3 alone, with weight
        :math:`OV_{thick}\,k_{stiff,1}`; :math:`v = SL_0\,\dot\Lambda`.
        ``Ka >= 0`` as long as the occupancies are.
        """
        OV_thick, _ = self._overlap(self._SL_curr)
        return self.p["SL0"] * OV_thick * self._kstiff1 * (self.p2_0 + self.p3_0)

    def bound_calcium_fraction(self) -> npt.NDArray[np.float64]:
        """
        Troponin C occupancy, ``TrpReg = (1 - OV_thin) CaL + OV_thin CaH``:
        the low-affinity sites in the non-overlap region and the
        high-affinity ones in the overlap region (Eq. (III)).
        """
        _, OV_thin = self._overlap(self._SL_curr)
        return (1.0 - OV_thin) * self.CaL + OV_thin * self.CaH

    def get_passive_tension(self) -> npt.NDArray[np.float64]:
        """Passive tension [kPa] of titin and collagen (Appendix C, Rice et al. 2008)."""
        p = self.p
        SL = self._SL_curr
        d = SL - p["SL_rest"]
        titin = np.sign(d) * p["PCon_titin"] * (np.exp(p["PExp_titin"] * np.abs(d)) - 1.0)
        collagen = np.where(
            SL >= p["SL_collagen"],
            p["PCon_collagen"] * (np.exp(p["PExp_collagen"] * (SL - p["SL_collagen"])) - 1.0),
            0.0,
        )
        return p["sigma_pas"] * (titin + collagen)

    def get_atp_hydrolysis_rate(self) -> npt.NDArray[np.float64]:
        """
        Crossbridge ATP hydrolysis rate [1/s per myosin head]: the flux through
        the irreversible A3 -> P detachment, k3 (p3_0 + alpha3 (s3^2 p3_0 +
        2 s3 p3_1 + p3_2)) -- Eq. (13) of Tewari et al. (2015), with strain.
        """
        a3, s3 = self.p["alpha3"], self.p["s3"]
        return self._k3 * (
            self.p3_0 + a3 * (s3 * s3 * self.p3_0 + 2.0 * s3 * self.p3_1 + self.p3_2)
        )
