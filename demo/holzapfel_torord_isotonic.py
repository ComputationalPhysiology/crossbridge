ax[0, 1].set_ylabel("Intracellular Ca (mM)")
ax[0, 1].set_title("Calcium Transient")

# Sarcomere Force
ax[1, 0].plot(t, Ta, color="red")
ax[1, 0].set_xlabel("Time (ms)")
ax[1, 0].set_ylabel("Active Tension, Ta (kPa)")
ax[1, 0].set_title("Active Stress Generation")

# Macroscopic Kinematics
ax[0, 2].plot(t, lmbdas, color="green")
ax[0, 2].set_ylabel(r"Stretch Ratio, $\lambda$")
ax[0, 2].set_title("Tissue Shortening")

ax[1, 1].plot(t, dLambdas, color="purple")
ax[1, 1].set_xlabel("Time (ms)")
ax[1, 1].set_ylabel(r"Stretch Rate ($d\lambda/dt$)")
ax[1, 1].set_title("Shortening Velocity")

ax[1, 2].plot(t, ps, color="brown")
ax[1, 2].set_xlabel("Time (ms)")
ax[1, 2].set_ylabel("Hydrostatic Pressure, p (kPa)")
ax[1, 2].set_title("Incompressibility Enforcement")

for axi in ax.flatten():
    axi.grid(True, alpha=0.3)

fig.tight_layout()
fig.savefig("holzapfel_torord_coupled.png")
